    private static final int[][] LOOKUP = new int[GRID][GRID];

    static {
        for (int[] row : LOOKUP) Arrays.fill(row, -1);
        for (int region = 0; region < CELLS.length; region++) {
            for (int index = 0; index < CELLS[region].length; index++) {
                int[] tile = CELLS[region][index];
                for (int v = tile[1]; v < tile[3]; v++) {
                    for (int u = tile[0]; u < tile[2]; u++) {
                        LOOKUP[v][u] = region * 1000 + index;
                    }
                }
            }
        }
    }

    private DonutGoliaths() {}

    static int square(int u, int v) {
        return u < 0 || v < 0 || u >= GRID || v >= GRID ? -1 : LOOKUP[v][u];
    }

    static int at(double x, double z) {
        int u = (int) Math.floor((x + HALF) / SQUARE);
        int v = (int) Math.floor((z + HALF) / SQUARE);
        return square(u, v);
    }
